class PresenceCache {

    constructor() {

        this.cache = new Map();

    }

    //////////////////////////////////////////////////////
    // SET
    //////////////////////////////////////////////////////

    set(userId, data) {

        this.cache.set(
            String(userId),
            {
                ...data,
                updatedAt: Date.now(),
            },
        );

    }

    //////////////////////////////////////////////////////
    // GET
    //////////////////////////////////////////////////////

    get(userId) {

        return this.cache.get(
            String(userId),
        );

    }

    //////////////////////////////////////////////////////
    // REMOVE
    //////////////////////////////////////////////////////

    remove(userId) {

        this.cache.delete(
            String(userId),
        );

    }

    //////////////////////////////////////////////////////
    // ONLINE
    //////////////////////////////////////////////////////

    isOnline(userId) {

        const user =
            this.get(userId);

        return user?.isOnline ?? false;

    }

    //////////////////////////////////////////////////////
    // LAST SEEN
    //////////////////////////////////////////////////////

    lastSeen(userId) {

        return this.get(userId)
            ?.lastSeen ?? null;

    }

    //////////////////////////////////////////////////////
    // TOTAL
    //////////////////////////////////////////////////////

    total() {

        return this.cache.size;

    }

}

module.exports =
    new PresenceCache();